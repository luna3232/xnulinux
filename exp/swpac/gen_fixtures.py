"""Emit fixtures.inc from an AArch64 object file and the matching assembly source."""
import struct
import sys


def text_bytes(path):
    data = open(path, "rb").read()
    if data[:4] != b"\x7fELF":
        raise SystemExit("not an ELF object: %s" % path)
    e_shoff = struct.unpack_from("<Q", data, 40)[0]
    e_shentsize = struct.unpack_from("<H", data, 58)[0]
    e_shnum = struct.unpack_from("<H", data, 60)[0]
    e_shstrndx = struct.unpack_from("<H", data, 62)[0]

    def shdr(i):
        return struct.unpack_from("<IIQQQQIIQQ", data, e_shoff + i * e_shentsize)

    shstr = shdr(e_shstrndx)
    strtab = data[shstr[4]:shstr[4] + shstr[5]]
    for i in range(e_shnum):
        hdr = shdr(i)
        name = strtab[hdr[0]:strtab.find(b"\0", hdr[0])].decode()
        if name == ".text":
            return data[hdr[4]:hdr[4] + hdr[5]]
    raise SystemExit("no .text in %s" % path)


def insns(path):
    out = []
    for line in open(path):
        s = line.split("//", 1)[0].strip()
        if not s or s.startswith(".") or s.startswith("/*") or s.startswith("*") or s == "*/" or s.endswith(":"):
            continue
        out.append(s)
    return out


def main():
    src, obj = sys.argv[1], sys.argv[2]
    blob = text_bytes(obj)
    lines = insns(src)
    if len(blob) != len(lines) * 4:
        raise SystemExit("instruction count %d != .text words %d" % (len(lines), len(blob) // 4))
    words = struct.unpack("<" + "I" * len(lines), blob)
    print("/* Generated by gen_fixtures.py from %s. Do not edit. */" % src)
    print("static const struct { uint32_t insn; const char *text; } swpac_fixtures[] = {")
    for word, text in zip(words, lines):
        esc = text.replace("\\", "\\\\").replace("\"", "\\\"")
        print("\t{ 0x%08xu, \"%s\" }," % (word, esc))
    print("};")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: gen_fixtures.py fixtures.s fixtures.o")
    main()
